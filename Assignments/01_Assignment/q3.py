#WAP to find quotient and remainder of two numbers.
user_input1 = int(input("Enter first number:-"))
user_input2 = int(input("Enter second number:-"))

quotient = user_input1 // user_input2

remainder = user_input1 % user_input2

print(f"Quotient of two number is {quotient}.")
print(f"remainder of two number is {remainder}.")